package com.quran.labs.androidquran.data

/** Page level actions available from the hafiz mode toolbar menu. */
enum class HafizPageAction {
  /** Reveal every ayah on the page. */
  REVEAL_ALL,

  /** Cover every ayah on the page. */
  HIDE_ALL,

  /** Reveal only the first word of every ayah on the page. */
  REVEAL_FIRST_WORD
}
